#!/usr/bin/env python3
"""panel2c.py <out.h> <file.txt>...

Turn the panel init sequences in board/allwinner/h700/panels/*.txt (one
"cmd data..." or "wait <hex ms>" per line, decoded from the vendor U-Boot
binaries) into the C table used by the disp2 anbernic panel driver.  Table
encoding: a length byte followed by that many bytes (command, parameters);
length 0 is followed by one byte: a delay in ms.  The C name of a table is
the file name with '-' turned into '_'.
"""
import os, sys

def load(path):
    out = bytearray()
    for line in open(path):
        line = line.split('#', 1)[0].strip()
        if not line:
            continue
        t = line.split()
        if t[0] == 'wait':
            ms = int(t[1], 16)
            if not 0 < ms < 256:
                raise SystemExit('%s: bad delay %s' % (path, line))
            out += bytes([0, ms])
        else:
            b = bytes(int(x, 16) for x in t)
            if not 0 < len(b) < 128:
                raise SystemExit('%s: bad command %s' % (path, line))
            out += bytes([len(b)]) + b
    return bytes(out)

out = sys.argv[1]
panels = []
for path in sys.argv[2:]:
    name = os.path.basename(path).rsplit('.', 1)[0]
    panels.append((name, name.replace('-', '_'), load(path)))

with open(out, 'w') as f:
    f.write('/* Generated by board/allwinner/h700/scripts/panel2c.py from\n'
            ' * board/allwinner/h700/panels/*.txt; do not edit. */\n\n')
    f.write('struct anbernic_panel {\n\tconst char *name;\n\tconst u8 *cmds;\n\tu32 cmds_len;\n};\n\n')
    for name, cname, b in panels:
        f.write('/* %s */\nstatic const u8 %s_cmds[%d] = {\n' % (name, cname, len(b)))
        for i in range(0, len(b), 16):
            f.write('\t' + ', '.join('0x%02x' % x for x in b[i:i + 16]) + ',\n')
        f.write('};\n\n')
    f.write('static const struct anbernic_panel anbernic_panels[] = {\n')
    for name, cname, b in panels:
        f.write('\t{ "%s", %s_cmds, sizeof(%s_cmds) },\n' % (name, cname, cname))
    f.write('};\n')
print('wrote', out, 'with', len(panels), 'panels')
