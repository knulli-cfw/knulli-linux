#!/usr/bin/env python3
"""gen_panels_h.py <panels.json> <out.h>: C init tables for the TrimUI A133
MIPI panels, from the json extracted out of the stock firmware."""
import json, sys

IDS = {
    'gc9702c':  '0x04 = 00 97 02',
    'otm1289a': '0x04 = 61 00 ..',
    'er68576':  '0x04 = e8.., 0xDA/DB/DC = e8 85 76',
    'st7703':   '0x04 = 38.., 0xDA/DB/DC = 38 21 1f',
    'nv3052':   '0x04 = 30.., 0xDA/DB/DC = 30 52 03',
    'jd9168':   '0x04 = 91.., 0xDA/DB/DC = 91 68 03',
    'gh7003':   '0xDA/DB/DC = 70 03 0a (Brick Pro)',
    'jd9168-pro': 'jd9168 on the Brick Pro (adds 0xCC)',
}
t = json.load(open(sys.argv[1]))
o = ['/* SPDX-License-Identifier: GPL-2.0 */',
     '/*',
     ' * TrimUI Brick (A133P) 1024x768 MIPI panel init tables, recovered from the',
     ' * stock firmware: the vendor U-Boot (boot_package u-boot.bin, "check_lcd_module")',
     ' * and the stock 4.9.191 kernel carry the same driver; nv3052 is U-Boot only,',
     ' * gh7003 and the jd9168 variant come from the Brick Pro U-Boot.',
     ' * Generated by gen_panels_h.py from trimui-brick-panels.json - do not edit.',
     ' *',
     ' * Variant detection (vendor U-Boot): DCS read 0x04 (3 bytes), 0xDA, 0xDB, 0xDC;',
     ' * then DA/DB/DC = 70 03 0a -> gh7003; no match -> jd9168 ("lcd=default").',
     ' */',
     '',
     'struct trimui_panel_cmd { u8 cmd; u8 len; u16 delay_ms; const u8 *data; };',
     '']
for name, ents in t.items():
    o.append('/* %s: %s */' % (name, IDS[name]))
    o.append('static const struct trimui_panel_cmd trimui_brick_%s[] = {' % name.replace('-', '_'))
    for c, p in ents:
        if c == 'delay':
            o.append('\t{ 0x00, 0, %d, NULL },' % p)
            continue
        b = bytes.fromhex(p)
        data = '(const u8[]){ %s }' % ', '.join('0x%02x' % x for x in b) if b else 'NULL'
        o.append('\t{ 0x%02x, %d, 0, %s },' % (c, len(b), data))
    o.append('\t{ 0xff, 0xff, 0, NULL }, /* end */')
    o.append('};')
    o.append('')
open(sys.argv[2], 'w').write('\n'.join(o))
